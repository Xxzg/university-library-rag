def make_pdf(title: str, pages: list[str], out: Path):
    doc = pymupdf.open()
    for text in pages:
        page = doc.new_page()
        # 中文长文本按行写入
        lines = text.strip().split("\n")
        y = 72
        for line in lines:
            page.insert_text((72, y), line, fontname="china-s", fontsize=11)
            y += 18
    doc.save(str(out))
    doc.close()
    print(f"[ok] {out.name}（PDF，{len(pages)} 页）")


def make_docx(title: str, paras: list[str], out: Path):
    doc = DocxDocument()
    for p in paras:
        style = "Heading 2" if p.startswith(("第", "1.", "2.", "3.", "4.")) else None
        if style and len(p) < 40:
            doc.add_heading(p, level=2)
        else:
            doc.add_paragraph(p)
    doc.save(str(out))
    print(f"[ok] {out.name}（DOCX，{len(paras)} 段）")


def make_md(title: str, content: str, out: Path):
    out.write_text(content, encoding="utf-8")
    print(f"[ok] {out.name}（Markdown）")


